'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
for (const [source, target] of [['catalog.js', 'Catalog.gs'], ['parser.js', 'Parse.gs'], ['engine.js', 'Engine.gs']]) {
  const input = path.join(root, 'core', source);
  if (!fs.existsSync(input)) throw new Error('Missing core module: ' + input);
  const contents = fs.readFileSync(input, 'utf8');
  fs.writeFileSync(path.join(root, 'apps-script', target), '// Generated from core/' + source + '. Edit the core source and rebuild.\n' + contents);
}
const bundle = '/** @OnlyCurrentDoc */\n// Generated by npm run bundle. Edit core/ or apps-script/Main.gs, then rebuild.\n\n' +
  ['Catalog.gs', 'Parse.gs', 'Engine.gs', 'Main.gs'].map(file => fs.readFileSync(path.join(root, 'apps-script', file), 'utf8').trimEnd()).join('\n\n') + '\n';
fs.mkdirSync(path.join(root, 'paste-into-apps-script'), {recursive:true});
fs.writeFileSync(path.join(root, 'paste-into-apps-script/ProjectPomfret.gs'), bundle);
console.log('Built paste-into-apps-script/ProjectPomfret.gs. Paste it into Code.gs in an empty scratch spreadsheet.');
