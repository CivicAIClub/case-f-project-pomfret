#!/usr/bin/env node
'use strict';
/* Input stays in memory. The only persisted output is a separate private artifact. */
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const parser = require('../core/parser.js');
const catalog = require('../core/catalog.js');
const ROOT = path.resolve(__dirname, '..');
const ARTIFACT = 'attached-data.js';
const MARKER = '// Case F private attachment data. Generated by prepare-local-data; do not commit.\n';
const diagnostics = {stage:'arguments'};
const SAFE_CODES = new Set(['INVALID_SOURCE','INVALID_SOURCE_FILE','INVALID_SOURCE_SHEET','INVALID_SOURCE_METADATA',
  'INVALID_PAYLOAD','UNVERIFIED_SOURCES','MISSING_GRADE','DUPLICATE_GRADE_TAB','INVALID_PROJECTS','INVALID_STUDENTS',
  'UNRESOLVED_SOURCE','INVALID_REFERENCES','INVALID_REFERENCE_FILE','INVALID_REFERENCE_METADATA','OUTPUT_INSIDE_CODE',
  'INVALID_OUTPUT_DIRECTORY','INVALID_OUTPUT_FILE','REFUSE_UNRELATED_FILE','INVALID_ARGUMENTS','INPUT_TOO_LARGE',
  'EACCES','EPERM','ENOENT','EEXIST','ENOTDIR','EISDIR']);

function inside(child, parent) {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith('..' + path.sep) && relative !== '..' && !path.isAbsolute(relative));
}

function validateSource(source, role) {
  if (!source || !Array.isArray(source.values) || !source.values.length || !Array.isArray(source.values[0])) throw new Error('INVALID_SOURCE');
  if (typeof source.sourceFile !== 'string' || path.basename(source.sourceFile) !== source.sourceFile || !source.sourceFile.endsWith('.xlsx')) throw new Error('INVALID_SOURCE_FILE');
  if (typeof source.originalSheet !== 'string' || !source.originalSheet.trim()) throw new Error('INVALID_SOURCE_SHEET');
  if (source.role !== role || !/^[a-f0-9]{64}$/.test(source.sha256 || '')) throw new Error('INVALID_SOURCE_METADATA');
}

function prepareData(payload, preparedAt = new Date().toISOString()) {
  if (!payload || payload.schemaVersion !== 1 || !Array.isArray(payload.tables) || payload.tables.length !== 3) throw new Error('INVALID_PAYLOAD');
  if (!payload.sourceIntegrity || payload.sourceIntegrity.unchanged !== true) throw new Error('UNVERIFIED_SOURCES');
  const grades = payload.tables.map(table => Number(table.grade)).sort();
  if (JSON.stringify(grades) !== '[10,11,12]') throw new Error('MISSING_GRADE');
  payload.tables.forEach(table => validateSource(table, 'student_responses'));
  validateSource(payload.projectTable, 'project_catalog');
  if (new Set(payload.tables.map(table => table.name)).size !== 3) throw new Error('DUPLICATE_GRADE_TAB');
  const parsedProjects = parser.parseProjects(payload.projectTable);
  if (!parsedProjects.projects.length || parsedProjects.issues.some(item => item.severity === 'error')) throw new Error('INVALID_PROJECTS');
  const projects = parsedProjects.projects.map(project => {
    // Metadata values come from the attached sheet; only verified title aliases are supplemented.
    const known = catalog.find(candidate => candidate.id === project.id);
    return {...project, aliases: [...new Set([...project.aliases, ...(known ? known.aliases : [])])]};
  });
  const prepared = parser.prepare(payload.tables, projects);
  const allowedReviewErrors = new Set(['IDENTITY_CONFLICT']);
  if (prepared.issues.some(item => item.severity === 'error' && !allowedReviewErrors.has(item.code))) throw new Error('INVALID_STUDENTS');
  const tableMap = new Map(payload.tables.map(table => [table.name, table]));
  const students = prepared.students.map(student => {
    const source = tableMap.get(student.source.sheet);
    if (!source) throw new Error('UNRESOLVED_SOURCE');
    return {...student, source: {...student.source, file: source.sourceFile, originalSheet: source.originalSheet}};
  });
  const sourceFiles = [...payload.tables, payload.projectTable].map(source => ({
    name: source.sourceFile, role: source.role, sheet: source.originalSheet,
    ...(source.grade ? {grade: Number(source.grade)} : {}), sha256: source.sha256,
  }));
  const referenceFiles = payload.referenceFiles || [];
  if (!Array.isArray(referenceFiles) || referenceFiles.length > 3) throw new Error('INVALID_REFERENCES');
  referenceFiles.forEach(source => {
    if (!source || typeof source.name !== 'string' || path.basename(source.name) !== source.name || !/\.(xlsx|docx|txt)$/.test(source.name)) throw new Error('INVALID_REFERENCE_FILE');
    if (!['historical_output_layout','requirements','later_defaults'].includes(source.role) || !/^[a-f0-9]{64}$/.test(source.sha256 || '')) throw new Error('INVALID_REFERENCE_METADATA');
    sourceFiles.push({name:source.name, role:source.role, sha256:source.sha256});
  });
  return {schemaVersion: 1, mode: 'attached', preparedAt, sourceFiles, projects, students,
    issues: [...parsedProjects.issues, ...prepared.issues], stats: prepared.stats,
    sourceIntegrity: {unchanged: true, method: 'SHA-256 checked before and after read-only source inspection'},
  };
}

function serializeData(data) {
  // A quoted JSON string is parsed as data. Raw HTML-closing text and JS line separators cannot escape it.
  const literal = JSON.stringify(JSON.stringify(data)).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return MARKER + 'var PPAttachedData = JSON.parse(' + literal + ');\n';
}

async function writePrivateData(outputDir, data) {
  const targetDir = path.resolve(outputDir);
  if (inside(targetDir, ROOT)) throw new Error('OUTPUT_INSIDE_CODE');
  await fs.mkdir(targetDir, {recursive: true, mode: 0o700});
  const directoryInfo = await fs.lstat(targetDir);
  if (!directoryInfo.isDirectory() || directoryInfo.isSymbolicLink()) throw new Error('INVALID_OUTPUT_DIRECTORY');
  const realDir = await fs.realpath(targetDir);
  if (inside(realDir, await fs.realpath(ROOT))) throw new Error('OUTPUT_INSIDE_CODE');
  await fs.chmod(targetDir, 0o700);
  const target = path.join(targetDir, ARTIFACT);
  try {
    const existing = await fs.lstat(target);
    if (!existing.isFile() || existing.isSymbolicLink()) throw new Error('INVALID_OUTPUT_FILE');
    const handle = await fs.open(target, 'r');
    let header;
    try {
      const bytes = Buffer.alloc(Buffer.byteLength(MARKER));
      const read = await handle.read(bytes, 0, bytes.length, 0);
      header = bytes.subarray(0, read.bytesRead).toString('utf8');
    } finally { await handle.close(); }
    if (header !== MARKER) throw new Error('REFUSE_UNRELATED_FILE');
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const temp = path.join(targetDir, '.attached-data-' + crypto.randomUUID() + '.tmp');
  let handle;
  try {
    handle = await fs.open(temp, 'wx', 0o600);
    await handle.writeFile(serializeData(data), 'utf8');
    await handle.sync();
    await handle.close(); handle = null;
    await fs.rename(temp, target);
    await fs.chmod(target, 0o600);
  } finally {
    if (handle) await handle.close();
    await fs.unlink(temp).catch(error => { if (error.code !== 'ENOENT') throw error; });
  }
  return target;
}

function aggregateReceipt(data) {
  const byStatus = data.stats.byStatus || {};
  return {status:'written', schemaVersion:1, sourceFiles:data.sourceFiles.length, students:data.students.length,
    eligible:(byStatus.eligible || 0) + (byStatus.late || 0), excluded:(byStatus.trip || 0) + (byStatus.leader || 0),
    review:byStatus.review || 0, projects:data.projects.filter(project => project.enabled).length,
    originalsUnchanged:data.sourceIntegrity.unchanged, artifact:ARTIFACT};
}

async function main() {
  const args = process.argv.slice(2);
  let outputDir = path.join(ROOT, '..', 'case-f-private');
  if (args.length) {
    if (args.length !== 2 || args[0] !== '--output-dir' || !args[1]) throw new Error('INVALID_ARGUMENTS');
    outputDir = args[1];
  }
  const chunks = [];
  let bytes = 0;
  diagnostics.stage = 'read_input';
  for await (const chunk of process.stdin) {
    bytes += chunk.length;
    if (bytes > 50 * 1024 * 1024) throw new Error('INPUT_TOO_LARGE');
    chunks.push(chunk);
  }
  diagnostics.stage = 'parse_input';
  const payload = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  diagnostics.stage = 'prepare_data';
  const data = prepareData(payload);
  diagnostics.stage = 'write_output';
  await writePrivateData(outputDir, data);
  diagnostics.stage = 'receipt';
  process.stdout.write(JSON.stringify(aggregateReceipt(data)) + '\n');
}

if (require.main === module) main().catch(error => {
  const code = SAFE_CODES.has(error.message) ? error.message : SAFE_CODES.has(error.code) ? error.code : diagnostics.stage === 'prepare_data' ? 'PARSER_ERROR' : 'UNEXPECTED_ERROR';
  const type = ['Error','TypeError','RangeError','SyntaxError'].includes(error.name) ? error.name : 'Error';
  process.stderr.write(JSON.stringify({status:'failed',stage:diagnostics.stage,code,type}) + '\n');
  process.exitCode = 1;
});
module.exports = {prepareData, serializeData, writePrivateData, aggregateReceipt};
