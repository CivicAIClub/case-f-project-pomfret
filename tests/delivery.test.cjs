'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {runPractice, exportPractice} = require('../scripts/demo.cjs');
const {build} = require('../scripts/build-public-demo.cjs');
const {createServer} = require('../scripts/serve-demo.cjs');
const root = path.resolve(__dirname, '..');

test('committed pasteable bundle matches shared source and keeps current-document scope', () => {
  for (const [source, file] of [['catalog.js','Catalog.gs'], ['parser.js','Parse.gs'], ['engine.js','Engine.gs']]) {
    assert.equal(fs.readFileSync(path.join(root, 'apps-script', file), 'utf8'),
      '// Generated from core/' + source + '. Edit the core source and rebuild.\n' + fs.readFileSync(path.join(root, 'core', source), 'utf8'));
  }
  const expected = '/** @OnlyCurrentDoc */\n// Generated by npm run bundle. Edit core/ or apps-script/Main.gs, then rebuild.\n\n' +
    ['Catalog.gs','Parse.gs','Engine.gs','Main.gs'].map(file => fs.readFileSync(path.join(root, 'apps-script', file), 'utf8').trimEnd()).join('\n\n') + '\n';
  assert.equal(fs.readFileSync(path.join(root, 'paste-into-apps-script/ProjectPomfret.gs'), 'utf8'), expected);
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'apps-script/appsscript.json'), 'utf8'));
  assert.deepEqual(manifest.oauthScopes, ['https://www.googleapis.com/auth/spreadsheets.currentonly']);
});

test('committed bundle runs practice, preparation, interest, sorting and recheck end to end', t => {
  const first = runPractice(), second = runPractice();
  assert.equal(first.result.fingerprint, second.result.fingerprint);
  assert.equal(first.result.assignments.length, 240);
  assert.equal(first.result.summary.placed, 240);
  assert.equal(first.result.summary.minorStudents, 88);
  assert.equal(first.result.summary.projectCount, 23);
  assert.equal(first.result.checks.filter(item => item.severity === 'error').length, 0);
  assert.ok(first.sheets.get('PP Check').data.length > 1, 'Review findings must remain visible.');
  for (const sheet of ['Senior','Junior','Sophomore']) {
    assert.equal(first.sheets.get(sheet).data.length, 81);
    assert.ok(first.sheets.get(sheet).data.slice(1).every(row => /^Practice Student \d{3}$/.test(row[2]) && /@example\.org$/.test(row[1])));
  }
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'case-f-demo-'));
  t.after(() => fs.rmSync(out, {recursive:true, force:true}));
  const exported = exportPractice(first, out);
  assert.deepEqual(exported.sort(), [...first.sheets.keys()].filter(name => name.startsWith('PP ')).map(name => name + '.csv').sort());
  assert.ok(exported.includes('PP Summary.csv') && exported.includes('PP Check.csv'));
  fs.writeFileSync(path.join(out, 'unrelated.txt'), 'keep');
  assert.throws(() => exportPractice(first, out), /Unexpected demo output/);
  assert.equal(fs.readFileSync(path.join(out, 'unrelated.txt'), 'utf8'), 'keep');
});

test('preview server serves generated practice assets and cannot serve source files', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'case-f-serve-'));
  t.after(() => fs.rmSync(directory, {recursive:true,force:true}));
  build(directory);
  const server = createServer(directory);
  await new Promise((resolve, reject) => { server.once('error',reject); server.listen(0,'127.0.0.1',resolve); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = 'http://127.0.0.1:' + server.address().port;
  const page = await fetch(url);
  assert.equal(page.status, 200);
  assert.match(await page.text(), /All students and responses are invented/);
  for (const name of ['/../package.json','/%2e%2e%2fpackage.json','/core/../../README.md','/.vercel/project.json','/attached-data.js']) {
    assert.equal((await fetch(url + name)).status, 404, name);
  }
});

test('public repository contains no school email addresses, school document links or local account paths', () => {
  const names = execFileSync('git', ['ls-files','--cached','--others','--exclude-standard','-z'], {cwd:root,encoding:'utf8'}).split('\0').filter(Boolean);
  assert.ok(names.includes('core/engine.js') && names.includes('README.md'));
  const schoolAddress = new RegExp('@' + 'pomfret' + '\\.org\\b', 'i');
  const schoolDocument = new RegExp('https?://' + 'docs' + '\\.google\\.com/(?:document|spreadsheets)/', 'i');
  const localAccount = new RegExp('/' + 'Users' + '/[a-zA-Z0-9_-]+/');
  for (const name of new Set(names)) {
    assert.doesNotMatch(name, /(?:^|\/)(?:attached-data\.(?:js|json)|\.env|project\.json)$|\.(?:xlsx|docx|zip)$/i, name);
    const contents = fs.readFileSync(path.join(root,name), 'utf8');
    for (const pattern of [schoolAddress, schoolDocument, localAccount]) assert.doesNotMatch(contents, pattern, name);
  }
});
